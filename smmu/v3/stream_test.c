static void __PreparationRollback(void)
{
    SMMUv3Unit_t* unit;
    SMMUv3Space_t* spaces[2] = {0};
    void* connections[2] = {0};
    ArmSMMUMemoryBlock_t blocks[512] = {0};
    uint32_t firstID = 0;
    uint32_t otherIDs[] = {1, 64, 128};
    uint64_t sharedTable;
    size_t blockCount = 0;
    size_t heapCount;
    unsigned int i;

    SMMUv3ModelBegin(false);
    unit = SMMUv3ModelStart();
    DMAIOMMUUnitLock(unit->Common.Backend);
    for (i = 0; i < 2; i++) {
        assert(SMMUv3SpaceCreate(unit, (void**)&spaces[i]) == OS_EOK);
    }
    assert(SMMUv3HardwareIDsPrepare(spaces[0], &firstID, 1, &connections[0]) == OS_EOK);
    sharedTable = unit->StreamTables[0].Block.PhysicalAddress;

    // Leave room for one new table. The second allocation must fail without
    // freeing the shared table or keeping any of the new SIDs reserved.
    while (MemoryStackFreeBlockCount(&unit->Common.Memory.FreePages) > 1) {
        assert(blockCount < sizeof(blocks) / sizeof(blocks[0]));
        assert(ArmSMMUMemoryAllocate(&unit->Common.Memory, 4096, 4096, &blocks[blockCount]) == OS_EOK);
        blockCount++;
    }
    heapCount = g_heapCount;
    assert(SMMUv3HardwareIDsPrepare(spaces[1], otherIDs, 3, &connections[1]) == OS_EOOM);
    assert(connections[1] == NULL && !spaces[1]->HasConnection);
    assert(g_heapCount == heapCount && MemoryStackFreeBlockCount(&unit->Common.Memory.FreePages) == 1);
    assert(unit->StreamTables[0].Block.PhysicalAddress == sharedTable);
    assert(unit->StreamTables[0].ReservedIDs == 1);
    assert(unit->StreamTables[1].Block.Length == 0 && unit->StreamTables[1].ReservedIDs == 0);
    assert(unit->StreamTables[2].Block.Length == 0 && unit->StreamTables[2].ReservedIDs == 0);
    assert(strstr(g_lastError, "__AllocateStreamTable: allocating L2 table 2 at 100000 failed:") == g_lastError);
    assert(DMAIOMMUUnitCheck(unit->Common.Backend) == OS_EOK);
    while (blockCount != 0) {
        blockCount--;
        assert(ArmSMMUMemoryFree(&unit->Common.Memory, &blocks[blockCount]) == OS_EOK);
    }

    assert(SMMUv3HardwareIDsPrepare(spaces[1], otherIDs, 3, &connections[1]) == OS_EOK);
    assert(SMMUv3HardwareIDsConnect(spaces[1], connections[1], ARM_SMMU_TIMEOUT_NS) == OS_EOK);
    assert(SMMUv3HardwareIDsDisconnect(spaces[1], connections[1], ARM_SMMU_TIMEOUT_NS) == OS_EOK);
    for (i = 0; i < 2; i++) {
        SMMUv3HardwareIDsDestroy(spaces[i], connections[i]);
        SMMUv3SpaceDestroy(unit, spaces[i]);
    }
    DMAIOMMUUnitUnlock(unit->Common.Backend);
    assert(SMMUv3UnitDestroy(&unit) == OS_EOK);
    SMMUv3ModelEnd();
}

static void __PartialConnectionAndSharedL1(void)
{
    SMMUv3Unit_t* unit;
    SMMUv3Space_t* a = NULL;
    SMMUv3Space_t* b = NULL;
    SMMUv3Space_t* c = NULL;
    void* first = NULL;
    void* second = NULL;
    void* conflict = NULL;
    uint32_t firstIDs[] = {0, 65535};
    uint32_t otherID = 1;
    uint32_t duplicates[] = {2, 2};
    uint64_t ignored;
    uint32_t producers;
    SMMUv3CommandBatch_t fill[2] = {0};
    ArmSMMUDeadline_t deadline;
    unsigned int i;

    SMMUv3ModelBegin(false);
    g_smmuv3Model.Registers[1] = 16U | (2U << 21) | (7U << 16);
    unit = SMMUv3ModelStart();
    // Cache the missing L1 before publication. No event is generated by this
    // direct model query, so it can test configuration-cache refresh in isolation.
    assert(SMMUv3ModelAccess(0, 0, false, &ignored) == OS_EDEVFAULT);
    DMAIOMMUUnitLock(unit->Common.Backend);
    assert(SMMUv3SpaceCreate(unit, (void**)&a) == OS_EOK);
    assert(SMMUv3SpaceCreate(unit, (void**)&b) == OS_EOK);
    assert(SMMUv3SpaceCreate(unit, (void**)&c) == OS_EOK);
    assert(SMMUv3HardwareIDsPrepare(a, duplicates, 2, &first) == OS_EINVALPARAMS && first == NULL);
    assert(SMMUv3HardwareIDsPrepare(a, firstIDs, 2, &first) == OS_EOK);
    assert(SMMUv3HardwareIDsPrepare(b, firstIDs, 2, &conflict) == OS_EEXISTS && conflict == NULL);
    assert(SMMUv3HardwareIDsPrepare(b, &otherID, 1, &second) == OS_EOK);
    g_noHeap = true;
    // Fill a four-entry command queue before A publishes its L1 pointer.
    // A then times out without submitting CFGI, so B cannot rely on A's SYNC.
    g_smmuv3Model.HoldCommands = true;
    g_smmuv3Model.TimeStep = 10000000;
    for (i = 0; i < 2; i++) {
        fill[i].Count = 2;
        fill[i].Commands[0].Words[0] = 0x28 | (1ULL << 32);
        fill[i].Commands[1].Words[0] = 0x46;
        assert(ArmSMMUDeadlineBegin(ARM_SMMU_TIMEOUT_NS, &deadline) == OS_EOK);
        assert(SMMUv3CommandBatchRun(unit, &fill[i], &deadline) == OS_ETIMEOUT);
    }
    assert(SMMUv3HardwareIDsConnect(a, first, ARM_SMMU_TIMEOUT_NS) == OS_ETIMEOUT);
    assert(unit->StreamTables[0].Published);
    assert(((SMMUv3Connection_t*)first)->Batch.State == SMMUv3BatchPrepared);
    g_smmuv3Model.HoldCommands = false;
    g_smmuv3Model.TimeStep = 1000;
    // B cannot treat A's published bit as proof of the non-leaf invalidation.
    assert(SMMUv3HardwareIDsConnect(b, second, ARM_SMMU_TIMEOUT_NS) == OS_EOK);
    assert(!g_smmuv3Model.L1Present[0]);
    assert(SMMUv3HardwareIDsDisconnect(a, first, ARM_SMMU_TIMEOUT_NS) == OS_EOK);
    SMMUv3HardwareIDsDestroy(a, first);
    g_noHeap = false;
    assert(SMMUv3HardwareIDsPrepare(c, firstIDs, 2, &conflict) == OS_EOK);
    g_noHeap = true;
    assert(SMMUv3HardwareIDsConnect(c, conflict, ARM_SMMU_TIMEOUT_NS) == OS_EOK);
    g_smmuv3Model.HoldSync = true;
    g_smmuv3Model.TimeStep = 10000000;
    assert(SMMUv3HardwareIDsDisconnect(c, conflict, ARM_SMMU_TIMEOUT_NS) == OS_ETIMEOUT);
    assert(unit->StreamTables[0].ReservedIDs & 1);
    producers = g_smmuv3Model.ProducerWrites;
    assert(SMMUv3HardwareIDsDisconnect(c, conflict, ARM_SMMU_TIMEOUT_NS) == OS_ETIMEOUT);
    assert(g_smmuv3Model.ProducerWrites == producers);
    g_smmuv3Model.HoldSync = false;
    g_smmuv3Model.TimeStep = 1000;
    assert(SMMUv3HardwareIDsDisconnect(c, conflict, ARM_SMMU_TIMEOUT_NS) == OS_EOK);
    SMMUv3HardwareIDsDestroy(c, conflict);
    assert(SMMUv3HardwareIDsDisconnect(b, second, ARM_SMMU_TIMEOUT_NS) == OS_EOK);
    SMMUv3HardwareIDsDestroy(b, second);
    assert(unit->StreamTables[0].ReservedIDs == 0 && unit->StreamTables[0].Block.Length == 4096);
    SMMUv3SpaceDestroy(unit, a);
    SMMUv3SpaceDestroy(unit, b);
    SMMUv3SpaceDestroy(unit, c);
    g_noHeap = false;
    DMAIOMMUUnitUnlock(unit->Common.Backend);
    assert(SMMUv3UnitDestroy(&unit) == OS_EOK);
    SMMUv3ModelEnd();
}

static void __EveryConnectPhase(void)
{
    SMMUv3Unit_t* unit;
    SMMUv3Space_t* space;
    void* connection;
    uint32_t sid = 64;
    unsigned int phase;

    for (phase = 0; phase < 4; phase++) {
        SMMUv3ModelBegin(false);
        unit = SMMUv3ModelStart();
        space = NULL;
        connection = NULL;
        DMAIOMMUUnitLock(unit->Common.Backend);
        assert(SMMUv3SpaceCreate(unit, (void**)&space) == OS_EOK);
        assert(SMMUv3HardwareIDsPrepare(space, &sid, 1, &connection) == OS_EOK);
        g_smmuv3Model.SyncStopAfter = g_smmuv3Model.Syncs + phase;
        // The zero phase means stop immediately after startup's existing SYNC.
        g_smmuv3Model.TimeStep = 1000000;
        assert(SMMUv3HardwareIDsConnect(space, connection, ARM_SMMU_TIMEOUT_NS) == OS_ETIMEOUT);
        assert(SMMUv3HardwareIDsConnect(space, connection, ARM_SMMU_TIMEOUT_NS) == OS_EBUSY);
        g_smmuv3Model.SyncStopAfter = 0;
        g_smmuv3Model.TimeStep = 1000;
        assert(SMMUv3HardwareIDsDisconnect(space, connection, ARM_SMMU_TIMEOUT_NS) == OS_EOK);
        SMMUv3HardwareIDsDestroy(space, connection);
        SMMUv3SpaceDestroy(unit, space);
        DMAIOMMUUnitUnlock(unit->Common.Backend);
        assert(SMMUv3UnitDestroy(&unit) == OS_EOK);
        SMMUv3ModelEnd();
    }
}

// Keep both roots populated during disconnect. Removing mappings first would
// conceal a stale route, since either root would then fault for the same IOVA.
static void __LiveRootsAndDisconnect(void)
{
    SMMUv3Unit_t* unit;
    SMMUv3Space_t* spaces[2] = {0};
    SMMUv3Mapping_t* mappings[2] = {0};
    void* connections[2] = {0};
    uint32_t sids[2] = {11, 12};
    SHMSG_t extents[2] = {{ .Address = 0x400000, .Length = 4096 },
                         { .Address = 0x800000, .Length = 4096 }};
    DMAIOMMUMappingConfig_t configs[2] = {
        { .DeviceAddress = 0x1000, .Length = 4096, .Direction = DMABidirectional,
          .Extents = &extents[0], .ExtentCount = 1 },
        { .DeviceAddress = 0x1000, .Length = 4096, .Direction = DMABidirectional,
          .Extents = &extents[1], .ExtentCount = 1 }
    };
    uint32_t oldVMID;
    uint64_t oldRoot;
    uint64_t physical;
    size_t blocks;
    unsigned int i;

    SMMUv3ModelBegin(false);
    unit = SMMUv3ModelStart();
    DMAIOMMUUnitLock(unit->Common.Backend);
    for (i = 0; i < 2; i++) {
        assert(SMMUv3SpaceCreate(unit, (void**)&spaces[i]) == OS_EOK);
        assert(SMMUv3MappingPrepare(spaces[i], &configs[i], (void**)&mappings[i]) == OS_EOK);
        assert(SMMUv3MappingInstall(spaces[i], mappings[i], ARM_SMMU_TIMEOUT_NS) == OS_EOK);
        assert(SMMUv3HardwareIDsPrepare(spaces[i], &sids[i], 1, &connections[i]) == OS_EOK);
        assert(SMMUv3HardwareIDsConnect(spaces[i], connections[i], ARM_SMMU_TIMEOUT_NS) == OS_EOK);
        assert(SMMUv3ModelAccess(sids[i], 0x1023, false, &physical) == OS_EOK);
        assert(physical == extents[i].Address + 0x23);
    }
    assert(spaces[0]->VMID != spaces[1]->VMID);
    oldVMID = spaces[0]->VMID;
    oldRoot = spaces[0]->Table.Root.PhysicalAddress;
    blocks = unit->Common.Memory.BlockCount;
    g_smmuv3Model.HoldSync = true;
    g_smmuv3Model.TimeStep = 10000000;
    assert(SMMUv3HardwareIDsDisconnect(spaces[0], connections[0], ARM_SMMU_TIMEOUT_NS) == OS_ETIMEOUT);
    assert(unit->Common.Memory.BlockCount == blocks && spaces[0]->Table.Root.PhysicalAddress == oldRoot);
    assert(unit->VMIDs[oldVMID / 64] & (1ULL << (oldVMID % 64)));
    assert(unit->StreamTables[0].ReservedIDs & (1ULL << 11));
    assert(SMMUv3ModelAccess(11, 0x1000, false, &physical) == OS_EOK && physical == extents[0].Address);
    g_smmuv3Model.HoldSync = false;
    g_smmuv3Model.TimeStep = 1000;
    assert(SMMUv3HardwareIDsDisconnect(spaces[0], connections[0], ARM_SMMU_TIMEOUT_NS) == OS_EOK);
    assert(SMMUv3ModelAccess(11, 0x1000, false, &physical) == OS_EDEVFAULT);
    for (i = 0; i < SMMUV3_MODEL_CACHE_ENTRIES; i++) {
        assert(!g_smmuv3Model.Translations[i].Present || g_smmuv3Model.Translations[i].VMID != oldVMID);
    }
    assert(SMMUv3ModelAccess(12, 0x1000, false, &physical) == OS_EOK && physical == extents[1].Address);
    SMMUv3HardwareIDsDestroy(spaces[0], connections[0]);
    assert(SMMUv3MappingRemove(spaces[0], mappings[0], ARM_SMMU_TIMEOUT_NS) == OS_EOK);
    SMMUv3MappingDestroy(spaces[0], mappings[0]);
    SMMUv3SpaceDestroy(unit, spaces[0]);
    spaces[0] = NULL;
    connections[0] = NULL;
    assert(SMMUv3SpaceCreate(unit, (void**)&spaces[0]) == OS_EOK && spaces[0]->VMID == oldVMID);
    assert(SMMUv3HardwareIDsPrepare(spaces[0], &sids[0], 1, &connections[0]) == OS_EOK);
    assert(SMMUv3HardwareIDsConnect(spaces[0], connections[0], ARM_SMMU_TIMEOUT_NS) == OS_EOK);
    assert(SMMUv3ModelAccess(11, 0x1000, false, &physical) == OS_EDEVFAULT);
    for (i = 0; i < 2; i++) {
        assert(SMMUv3HardwareIDsDisconnect(spaces[i], connections[i], ARM_SMMU_TIMEOUT_NS) == OS_EOK);
        SMMUv3HardwareIDsDestroy(spaces[i], connections[i]);
        if (i == 1) {
            assert(SMMUv3MappingRemove(spaces[i], mappings[i], ARM_SMMU_TIMEOUT_NS) == OS_EOK);
            SMMUv3MappingDestroy(spaces[i], mappings[i]);
        }
        SMMUv3SpaceDestroy(unit, spaces[i]);
    }
    DMAIOMMUUnitUnlock(unit->Common.Backend);
    assert(SMMUv3UnitDestroy(&unit) == OS_EOK);
    SMMUv3ModelEnd();
}

void SMMUv3StreamTests(void)
{
    __PreparationRollback();
    __LiveRootsAndDisconnect();
    __PartialConnectionAndSharedL1();
    __EveryConnectPhase();
}
